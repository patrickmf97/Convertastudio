  const WA_NUMBER = '5521988761259';
  const WA_STATIC_MSG = {
    pt:'Olá! Vim pela página do Converta Studio e quero saber mais sobre uma landing page.',
    en:"Hi! I came from the Converta Studio page and I'd like to know more about a landing page.",
    es:'¡Hola! Llegué desde la página de Converta Studio y quiero saber más sobre una landing page.'
  };
  const FX_LABEL = {
    en: (live) => live ? 'Live currency conversion (BRL → USD)' : 'Exchange rate unavailable — price shown in BRL',
    es: (live) => live ? 'Conversión de moneda en vivo (BRL → ARS)' : 'Cotización no disponible — precio mostrado en BRL'
  };

  let lang = 'pt';
  let rateUSD = 0.19;   // fallback, replaced by live fetch
  let rateARS = 292;    // fallback, replaced by live fetch
  let fxLive = false;

  function applyTranslations(){
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if(T[key] && T[key][lang] !== undefined){
        el.innerHTML = T[key][lang];
      }
    });
    document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));

    // fx notes
    const fxNote = document.getElementById('fx-note');
    const fxNotePrice = document.getElementById('fx-note-price');
    const fxDot = document.getElementById('fx-dot');
    const fxDotPrice = document.getElementById('fx-dot-price');
    const fxText = document.getElementById('fx-text');
    const fxTextPrice = document.getElementById('fx-text-price');
    if(lang === 'pt'){
      fxNote?.classList.remove('show');
      fxNotePrice?.classList.remove('show');
    } else {
      const label = FX_LABEL[lang](fxLive);
      if (fxText) fxText.textContent = label;
      if (fxTextPrice) fxTextPrice.textContent = label;
      fxDot?.classList.toggle('stale', !fxLive);
      fxDotPrice?.classList.toggle('stale', !fxLive);
      fxNote?.classList.add('show');
      fxNotePrice?.classList.add('show');
    }

    document.getElementById('cta-final-link').href = 'https://wa.me/' + WA_NUMBER + '?text=' + encodeURIComponent(WA_STATIC_MSG[lang]);
    updateTotal();
    updatePriceCard();
  }

  function formatPrice(brlValue){
    if(lang === 'pt' || !fxLive){
      return 'R$ ' + Math.round(brlValue).toLocaleString('pt-BR');
    } else if(lang === 'en'){
      const usd = brlValue * rateUSD;
      return 'US$ ' + Math.round(usd).toLocaleString('en-US');
    } else {
      const ars = brlValue * rateARS;
      return '$ ' + Math.round(ars).toLocaleString('es-AR') + ' ARS';
    }
  }

  function updatePriceCard(){
    const priceValue = document.getElementById('price-value');
    if (priceValue) priceValue.textContent = formatPrice(497);
  }

  // ---------- Calculator ----------
  const state = { sections: 0, revisions: 0, prazo: 0 };
  const base = 497;
  const valueEl = document.getElementById('calc-value');
  const ctaEl = document.getElementById('calc-cta');

  const DETAIL_PARTS = {
    pt: { sections:'estrutura completa (até 8 seções)', rev1:'+1 revisão extra', rev2:'+2 revisões extras', rush:'entrega urgente (3 dias úteis)', join:' com ' },
    en: { sections:'complete structure (up to 8 sections)', rev1:'+1 extra revision', rev2:'+2 extra revisions', rush:'rush delivery (3 business days)', join:' with ' },
    es: { sections:'estructura completa (hasta 8 secciones)', rev1:'+1 revisión extra', rev2:'+2 revisiones extra', rush:'entrega urgente (3 días hábiles)', join:' con ' }
  };
  const WA_CALC_TEMPLATE = {
    pt: (detail, price) => `Olá! Vim pela página do Converta Studio. Fiz uma estimativa: landing page${detail}, valor aproximado de ${price}. Podemos conversar?`,
    en: (detail, price) => `Hi! I came from the Converta Studio page. I made an estimate: landing page${detail}, approximate value of ${price}. Can we talk?`,
    es: (detail, price) => `¡Hola! Llegué desde la página de Converta Studio. Hice una estimación: landing page${detail}, valor aproximado de ${price}. ¿Podemos hablar?`
  };

  function updateTotal(){
    const totalBRL = base + state.sections + state.revisions + state.prazo;
    const formatted = formatPrice(totalBRL);
    valueEl.textContent = formatted;

    const d = DETAIL_PARTS[lang];
    const parts = [];
    if(state.sections > 0) parts.push(d.sections);
    if(state.revisions === 50) parts.push(d.rev1);
    if(state.revisions === 100) parts.push(d.rev2);
    if(state.prazo > 0) parts.push(d.rush);
    const detail = parts.length ? d.join + parts.join(', ') : '';

    const msg = WA_CALC_TEMPLATE[lang](detail, formatted);
    ctaEl.href = 'https://wa.me/' + WA_NUMBER + '?text=' + encodeURIComponent(msg);
  }

  document.querySelectorAll('.opts').forEach(group => {
    const key = group.dataset.group;
    group.querySelectorAll('.opt').forEach(btn => {
      btn.addEventListener('click', () => {
        group.querySelectorAll('.opt').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        state[key] = parseInt(btn.dataset.value, 10);
        updateTotal();
      });
    });
  });

  // ---------- Language switcher ----------
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      lang = btn.dataset.lang;
      applyTranslations();
    });
  });

  // ---------- Live FX fetch ----------
  fetch('https://open.er-api.com/v6/latest/BRL')
    .then(r => r.json())
    .then(data => {
      if(data && data.rates && data.rates.USD && data.rates.ARS){
        rateUSD = data.rates.USD;
        rateARS = data.rates.ARS;
        fxLive = true;
      }
    })
    .catch(() => { fxLive = false; })
    .finally(() => { applyTranslations(); });

  // ---------- Sticky header shadow ----------
  const headerEl = document.getElementById('site-header');
  window.addEventListener('scroll', () => {
    headerEl.classList.toggle('scrolled', window.scrollY > 8);
  });


  // Initial render (uses fallback rates until fetch resolves)
  applyTranslations();
